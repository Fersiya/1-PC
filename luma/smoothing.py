"""Сглаживание цвета: не зависит от FPS и быстро реагирует на резкую смену сцены."""


def smooth_alpha(smoothing: float, dt: float, diff: float) -> float:
    """Доля старого значения (0..1) для одного шага.

    smoothing — настройка 0..0.9 (инерция при ~20 кадрах/с);
    dt — секунды с прошлого шага; diff — суммарная разница RGB (0..765).
    Малые изменения сглаживаются сильнее, резкие (смена сцены) проходят почти сразу.
    """
    if smoothing <= 0.0:
        return 0.0
    dt = max(0.005, min(0.5, dt))
    alpha = smoothing ** (dt * 20.0)  # одинаковая «скорость» при любом FPS
    boost = min(1.0, max(0.0, (diff - 60.0) / 240.0))  # 0 при diff<=60, 1 при diff>=300
    return alpha * (1.0 - 0.8 * boost)
